#!/usr/bin/env node
/**
 * Derive coreVocab.js from PHRASE_BREAKDOWNS.
 *
 * Purpose: produce a canonical list of every Japanese word token the learner
 * has encountered (or will encounter) via the 400-phrase curriculum. Scene +
 * story scripts must stay within this set, with up to 4 flagged new words
 * per scene / 3 per story as the only exceptions.
 *
 * Output: src/data/coreVocab.js exporting a Set-like map.
 *
 * Run:  PATH="/usr/local/bin:$PATH" node scripts/build-core-vocab.mjs
 */
import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dir = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dir, '..');

const { PHRASE_BREAKDOWNS } = await import(join(ROOT, 'src/data/phraseBreakdowns.js'));

const byToken = new Map();

for (const [phraseId, segments] of Object.entries(PHRASE_BREAKDOWNS)) {
  for (const [jp, romaji, en, type] of segments) {
    if (!jp || jp === '...' || jp === '/ ' || jp === '/') continue;
    const key = jp.trim();
    if (!key) continue;
    if (!byToken.has(key)) {
      byToken.set(key, { jp: key, romaji, en, type, firstSeen: phraseId });
    }
  }
}

const rows = [...byToken.values()].sort((a, b) => a.jp.localeCompare(b.jp, 'ja'));

const body = [
  '// Auto-generated by scripts/build-core-vocab.mjs — do not edit by hand.',
  '// Re-run whenever phrases.js or phraseBreakdowns.js changes.',
  '// Every Japanese token here is "known vocabulary" for the learner.',
  '// Scene + story scripts must stay within this set (+ flagged newWords).',
  '',
  'export const CORE_VOCAB = [',
  ...rows.map(r => `  { jp: ${JSON.stringify(r.jp)}, romaji: ${JSON.stringify(r.romaji)}, en: ${JSON.stringify(r.en)}, type: ${JSON.stringify(r.type)}, firstSeen: ${JSON.stringify(r.firstSeen)} },`),
  '];',
  '',
  'export const CORE_VOCAB_SET = new Set(CORE_VOCAB.map(v => v.jp));',
  '',
  '// Lookup: jp → {romaji, en, type, firstSeen}',
  'export const CORE_VOCAB_BY_JP = Object.fromEntries(CORE_VOCAB.map(v => [v.jp, v]));',
  '',
].join('\n');

const out = join(ROOT, 'src/data/coreVocab.js');
writeFileSync(out, body);
console.log(`✓ Wrote ${rows.length} tokens to src/data/coreVocab.js`);
